# Crie dois números e apresente:
# - Soma.
soma = 2 + 2
# - Subtração.
subtracao = 2 - 2
# - Multiplicação.
multiplicacao = 2 * 2
# - Divisão.
divisao = 2 / 2
# - Divisão inteira.
divisao_inteira = 2 // 2
# - Resto da divisão.
resto_da_divisao = 2 % 2
# - Potência.
potencia = 2 ** 2

print(soma)
print(subtracao)
print(multiplicacao)
print(divisao)
print(divisao_inteira)
print(resto_da_divisao)
print(potencia)

# Crie um programa que:
# - Pergunte a idade do usuário.
idade_usuario = int(input('Qual sua idade? '))
# - Verifique se ele tem 18 anos ou mais.
if idade_usuario >= 18:
# - Se tiver, mostre "Maior de idade".
    print('Maior de idade')
# - Caso contrário, mostre "Menor de idade".
else:
    print('Menor de idade')